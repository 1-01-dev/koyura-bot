"""Cookie jars the engine hands to yt-dlp, and which file to try next.

A service that wants a logged-in account (Reddit's NSFW subs, an age-gated
video, a private post) accepts a Netscape cookie jar through ``--cookies``. The
operator uploads those jars in the panel, which owns them; this module is the
engine's side of that bargain:

* **where they are** — ``COOKIES_PATH/<service>/<file>.txt``, the same tree the
  panel writes, mounted into this container read-only;
* **which ones** — the ordered list the panel publishes, because the order *is*
  the retry order: the first jar is tried, and only an authorization failure
  moves on to the second. The registry is cached for a minute, so a download
  does not pay for a round trip to the panel and a newly added jar is picked up
  without a restart;
* **which service a URL belongs to** — yt-dlp's own extractor table decides
  (``RedditIE.suitable(url)``), so nothing here hard-codes a site name.

Two properties matter beyond that:

* **the secret never leaves the disk.** A path is a name, the file is read by
  yt-dlp itself, and no log line here contains a cookie. A failure is reported
  with the service name only.
* **an unreachable panel is not an outage.** Without the registry the engine
  still finds the jars on disk (sorted, deterministic order) and downloads work;
  the retry order is then simply alphabetical.
"""
from __future__ import annotations

import json
import logging
import os
import re
import threading
import time
import urllib.error
import urllib.request
from pathlib import Path

logger = logging.getLogger("koyura.engine.cookies")

#: The tree the panel writes; the only name the code reads.
DEFAULT_COOKIES_PATH = "/var/lib/koyura2/cookies"

#: The panel publishes the registry; it is polled at most this often. Under a
#: minute so an operator who adds a jar sees it take effect without a restart.
REGISTRY_TTL_SECONDS = 60.0
REGISTRY_PATH = "/api/services-with-cookies"

#: A dashboard that cannot answer in two seconds must not delay a download.
_TIMEOUT_SECONDS = 2.0

#: Mirrors ``dashboard/service_cookies.py``: one safe path component. A run of
#: separators collapses to one dash, so ``abc/../x`` is ``abc-x`` and no dotted
#: traversal survives in either service.
_SEPARATOR_RUN = re.compile(r"[-._]{2,}")
_SERVICE_STRIP = re.compile(r"[^a-z0-9._-]+")
_SERVICE_ALLOWED = re.compile(r"[a-z0-9._-]+")

#: Stored file names are generated by the panel.
_STORED_NAME = re.compile(r"[a-z0-9]{8,32}\.txt")

#: Substrings yt-dlp / the site emit when the session is not good enough. All of
#: them mean the same thing to us: "try the next jar", never "give up yet".
AUTH_MARKERS = (
    "sign in to confirm",
    "login required",
    "log in to confirm",
    "private video",
    "http error 403",
    "cookies",
    "this video is private",
    "age-restricted",
    "age restricted",
    "confirm your age",
    "nsfw",
    "unauthorized",
)

#: The site refused the **address**, not the session. Mirrors
#: ``dashboard/service_cookies.py``: this is what a datacentre block looks like
#: (Reddit's API 403, Cloudflare's page, a rate limit, a captcha wall), and no
#: cookie jar can fix it — only another outbound IP, which is what the panel's
#: Proxy page configures. Checked before ``AUTH_MARKERS`` because "HTTP Error
#: 403: Blocked" contains the generic 403 marker: retrying the next jar would
#: burn a minute to learn the same thing again.
BLOCKED_MARKERS = (
    "unable to access the reddit api",
    "http error 403: blocked",
    "blocked",
    "too many requests",
    "429",
    "captcha",
)


def cookies_root() -> Path:
    """Root of the cookie tree (``COOKIES_PATH``, read per call)."""
    raw = os.environ.get("COOKIES_PATH", "").strip() or DEFAULT_COOKIES_PATH
    return Path(raw)


def sanitise_service(raw: object) -> str:
    """Lowercase ``raw`` into one safe path component (mirrors the panel)."""
    text = str(raw or "").strip().lower().split(":")[0]
    text = _SERVICE_STRIP.sub("-", text)
    text = _SEPARATOR_RUN.sub("-", text).strip("-.")
    if not text or len(text) > 64 or ".." in text:
        return ""
    return text if _SERVICE_ALLOWED.fullmatch(text) else ""


def dashboard_url() -> str:
    """Address of the admin panel (``KOYURA_DASHBOARD_URL``, else compose)."""
    value = os.environ.get("KOYURA_DASHBOARD_URL", "").strip()
    return (value or "http://dashboard:8080").rstrip("/")


# ---------------------------------------------------------------------------
# Registry (the panel owns the order)
# ---------------------------------------------------------------------------

_registry_lock = threading.Lock()
_registry: dict[str, list[str]] = {}
_registry_expires = 0.0


def parse_registry(payload: object) -> dict[str, list[str]]:
    """Turn the panel's answer into ``{service: [stored_name, …]}``.

    The response is read tolerantly: the panel answers
    ``{"services": [{"service": "reddit", "files": [...]}, …]}``, and a plain
    list of names is accepted too, so a panel and an engine from neighbouring
    releases still work together. Every name is sanitised and every file name
    must look generated, so a hostile or corrupted answer cannot widen the
    tree the engine reads.
    """
    services: dict[str, list[str]] = {}
    entries = payload.get("services") if isinstance(payload, dict) else payload
    if not isinstance(entries, list):
        return {}
    for entry in entries:
        if isinstance(entry, str):
            name = sanitise_service(entry)
            files: list[str] = []
        elif isinstance(entry, dict):
            name = sanitise_service(entry.get("service"))
            files = [
                str(item) for item in (entry.get("files") or [])
                if _STORED_NAME.fullmatch(str(item))
            ]
        else:
            continue
        if name:
            services[name] = files
    return services


def _panel_registry() -> dict[str, list[str]]:
    """Fetch and parse the panel's registry; ``{}`` when it cannot answer."""
    token = os.environ.get("INTERNAL_API_TOKEN", "").strip()
    headers = {"X-Internal-Token": token} if token else {}
    request_obj = urllib.request.Request(  # noqa: S310 - fixed internal URL
        f"{dashboard_url()}{REGISTRY_PATH}",
        headers=headers,
        method="GET",
    )
    try:
        with urllib.request.urlopen(request_obj, timeout=_TIMEOUT_SECONDS) as response:  # noqa: S310
            payload = json.loads(response.read().decode("utf-8", "replace"))
    except (urllib.error.URLError, OSError, TimeoutError, ValueError) as exc:
        logger.debug("Cookie registry unavailable: %s", exc)
        return {}
    return parse_registry(payload)


def registry() -> dict[str, list[str]]:
    """The cached ``{service: ordered files}`` map (60 s, never raises)."""
    global _registry, _registry_expires
    now = time.monotonic()
    with _registry_lock:
        if now < _registry_expires:
            return dict(_registry)
    fetched = _panel_registry()
    with _registry_lock:
        if fetched:
            _registry = fetched
        else:
            # Keep the last good answer: a panel restart must not turn every
            # download into a cookie-less attempt.
            _registry = dict(_registry)
        if not _registry:
            # No panel and nothing cached: fall back to what is on disk so the
            # engine still works when the panel has never run.
            _registry = {name: [] for name in disk_services()}
        _registry_expires = now + REGISTRY_TTL_SECONDS
        return dict(_registry)


def reset_registry_cache() -> None:
    """Forget the cached registry (tests, and after a panel-triggered check)."""
    global _registry, _registry_expires
    with _registry_lock:
        _registry = {}
        _registry_expires = 0.0


# ---------------------------------------------------------------------------
# Files
# ---------------------------------------------------------------------------

def disk_services() -> list[str]:
    """Service directories that exist in ``COOKIES_PATH``, sorted."""
    root = cookies_root()
    try:
        return sorted(
            entry.name for entry in root.iterdir()
            if entry.is_dir() and _SERVICE_ALLOWED.fullmatch(entry.name)
        )
    except OSError:
        return []


def disk_files(service: object) -> list[str]:
    """``<id>.txt`` files present for one service, name-sorted (fallback order)."""
    name = sanitise_service(service)
    if not name:
        return []
    directory = cookies_root() / name
    try:
        return sorted(
            entry.name for entry in directory.iterdir()
            if entry.is_file() and _STORED_NAME.fullmatch(entry.name)
        )
    except OSError:
        return []


def cookie_paths(service: object) -> list[str]:
    """Ordered, existing jar paths for ``service`` (``[]`` when it has none).

    The order comes from the panel (upload order, rearranged by the operator);
    a file the panel lists but that is not on disk is skipped, and a file on
    disk the panel does not list is only used when the panel has no answer at
    all — a stale registry must not hide a jar the user just uploaded.
    """
    name = sanitise_service(service)
    if not name:
        return []
    listed = registry().get(name)
    names = listed if listed else disk_files(name)
    paths: list[str] = []
    for stored in names:
        candidate = cookies_root() / name / stored
        if candidate.is_file():
            paths.append(str(candidate))
    return paths


def has_cookies(service: object) -> bool:
    """Whether ``service`` has at least one usable jar right now."""
    return bool(cookie_paths(service))


# ---------------------------------------------------------------------------
# Which service does a URL belong to?
# ---------------------------------------------------------------------------

#: Generic extractors match nearly everything; they are never a service name.
_GENERIC_EXTRACTORS = frozenset({"generic", "url", "fallback"})


def _extractor_service(extractor: object) -> str:
    """``Reddit`` / ``reddit:subreddit`` → ``reddit``."""
    text = str(extractor or "").strip().lower()
    text = text.split(":")[0].strip()
    return sanitise_service(text)


def _iter_extractors():
    """yt-dlp's extractor instances, or nothing when the import fails."""
    try:
        from yt_dlp.extractor import gen_extractor_classes
    except Exception:  # pragma: no cover - yt-dlp is a hard requirement
        logger.warning("yt-dlp is not importable; cookie lookup by URL is off")
        return []
    try:
        return list(gen_extractor_classes())
    except Exception:  # pragma: no cover - defensive, a plugin raised
        logger.exception("Could not enumerate the yt-dlp extractors")
        return []


def service_for_url(url: object) -> str:
    """The cookie service a URL belongs to, or ``""`` when there is none.

    The most specific matching extractor wins: yt-dlp's own table is asked
    (``IE.suitable(url)``), generic extractors are ignored, and the result is
    the ``IE_NAME`` the panel offers as a suggestion — so ``youtube.com`` maps
    to ``youtube`` and nothing in this repository names a site.

    A page the extractor's regex does not cover (a subreddit front page, a
    profile) still belongs to the same service, so a host is the fallback: the
    registrable label of ``old.reddit.com`` is matched against the extractor
    names. Still yt-dlp's list, still no site list here.
    """
    text = str(url or "").strip()
    if not text:
        return ""
    extractors = list(_iter_extractors())
    for extractor in extractors:
        name = _extractor_service(getattr(extractor, "IE_NAME", ""))
        if not name or name in _GENERIC_EXTRACTORS:
            continue
        try:
            if extractor.suitable(text):
                return name
        except Exception:  # pragma: no cover - a plugin's regex can raise
            logger.debug("Extractor %s raised while matching a URL", name)
            continue
    return _service_for_host(text, extractors)


def _service_for_host(url: str, extractors: list) -> str:
    """Best-effort service for a URL no extractor regex claimed.

    Only a label that is also an extractor name counts, and the longest one
    wins (``redditmedia`` before ``reddit``), so this cannot invent a service
    that has no cookies folder to look in.
    """
    from urllib.parse import urlsplit

    try:
        host = (urlsplit(url).hostname or "").lower()
    except ValueError:
        return ""
    if not host:
        return ""
    known = {
        _extractor_service(getattr(extractor, "IE_NAME", ""))
        for extractor in extractors
    }
    known.discard("")
    for label in sorted(host.split("."), key=len, reverse=True):
        if label and label not in _GENERIC_EXTRACTORS and label in known:
            return label
    return ""


def service_from_info(info: object) -> str:
    """The service an already-fetched info payload came from.

    ``extractor_key`` is the class name (``Reddit``); ``extractor`` the
    ``IE_NAME`` (``reddit:subreddit``). Either one is enough, and the key is
    preferred because it is stable across sub-extractors.
    """
    if not isinstance(info, dict):
        return ""
    for field_name in ("extractor_key", "extractor"):
        name = _extractor_service(info.get(field_name))
        if name and name not in _GENERIC_EXTRACTORS:
            return name
    return ""


# ---------------------------------------------------------------------------
# Failure classification and the CLI
# ---------------------------------------------------------------------------

def looks_like_auth_failure(stderr: object) -> bool:
    """Whether yt-dlp's output says "this session is not allowed in"."""
    text = str(stderr or "").lower()
    return any(marker in text for marker in AUTH_MARKERS)


def looks_blocked(stderr: object) -> bool:
    """Whether the site refused *the address* rather than the session.

    A blocked IP is not a cookie problem: another jar answers the same 403.
    Separate from :func:`looks_like_auth_failure` so a job can stop after the
    first refusal and name the real cause to the user.
    """
    text = str(stderr or "").lower()
    return any(marker in text for marker in BLOCKED_MARKERS)


def with_cookies(cmd: list[str], path: str) -> list[str]:
    """A copy of ``cmd`` with ``--cookies <path>`` before the trailing URL.

    yt-dlp accepts options after the URL, but keeping them in the option block
    means the vector reads the way the documentation does — and a future
    argument appended after the URL cannot swallow our flag.
    """
    if not cmd:
        return ["--cookies", path]
    return [*cmd[:-1], "--cookies", path, cmd[-1]]


def required_message(service: object) -> str:
    """The sentence a user and the panel both show for a spent service.

    Deliberately short and free of any cookie detail: it says which service
    wants a session and what the operator has to do about it.
    """
    name = sanitise_service(service) or "this site"
    return (
        f"{name} needs a signed-in session (cookies). "
        "Add a cookie file in the panel: Admin → Storage."
    )


def blocked_message(service: object) -> str:
    """The sentence for a service that refuses the server's address.

    Says what actually helps (another outbound IP, i.e. the Proxy page) and
    explicitly not what does not (a fresh cookie file), because "403" reads
    like a sign-in problem to everyone who has not met a datacentre block.
    """
    name = sanitise_service(service) or "this site"
    return (
        f"{name} blocks this server's IP address. "
        "Cookies will not help — route the engine through a proxy or a "
        "WireGuard tunnel in the panel: Admin → Proxy."
    )


def cookie_required_payload(service: object) -> dict[str, object]:
    """The ``cookies_required`` body the API returns (additive to old keys)."""
    name = sanitise_service(service)
    return {
        "error": required_message(name),
        "code": "cookies_required",
        "service": name,
        "cookies_tried": 0,
    }


def blocked_payload(service: object) -> dict[str, object]:
    """The ``service_blocked`` body the API returns (additive to old keys)."""
    name = sanitise_service(service)
    return {
        "error": blocked_message(name),
        "code": "service_blocked",
        "service": name,
    }
