class TestOrder:
    def _add(self, service: str = "reddit") -> list[dict]:
        rows = []
        for index in range(3):
            name, digest, size = service_cookies.write_cookie_file(service, NETSCAPE)
            rows.append(
                asyncio.run(
                    db.add_service_cookie(
                        service=service,
                        stored_name=name,
                        original_name=f"file-{index}.txt",
                        size=size,
                        sha256=digest,
                    )
                )
            )
        return rows

    def test_files_are_appended_in_upload_order(self):
        rows = self._add()
        assert [row["position"] for row in rows] == [0, 1, 2]
        assert [row["original_name"] for row in _rows("reddit")] == [
            "file-0.txt", "file-1.txt", "file-2.txt",
        ]

    def test_moving_up_promotes_one_file(self):
        rows = self._add()
        third = rows[2]
        assert asyncio.run(db.move_service_cookie(int(third["id"]), -1)) is True

        names = [row["original_name"] for row in _rows("reddit")]
        assert names == ["file-0.txt", "file-2.txt", "file-1.txt"]
        assert [row["position"] for row in _rows("reddit")] == [0, 1, 2]

    def test_moving_down_demotes_one_file(self):
        rows = self._add()
        first = rows[0]
        asyncio.run(db.move_service_cookie(int(first["id"]), 1))

        names = [row["original_name"] for row in _rows("reddit")]
        assert names == ["file-1.txt", "file-0.txt", "file-2.txt"]

    def test_a_move_at_the_edge_is_a_harmless_no_op(self):
        rows = self._add()
        assert asyncio.run(db.move_service_cookie(int(rows[0]["id"]), -1)) is True
        assert asyncio.run(db.move_service_cookie(int(rows[2]["id"]), 1)) is True
        assert [row["original_name"] for row in _rows("reddit")] == [
            "file-0.txt", "file-1.txt", "file-2.txt",
        ]

    def test_positions_stay_dense_after_a_delete(self):
        rows = self._add()
        asyncio.run(db.delete_service_cookie(int(rows[1]["id"])))
        remaining = _rows("reddit")
        assert [row["position"] for row in remaining] == [0, 1]
        assert [row["original_name"] for row in remaining] == [
            "file-0.txt", "file-2.txt",
        ]

    def test_the_next_upload_takes_the_last_position(self):
        self._add()
        name, digest, size = service_cookies.write_cookie_file("reddit", NETSCAPE)
        row = asyncio.run(
            db.add_service_cookie(
                service="reddit", stored_name=name, original_name="file-3.txt",
                size=size, sha256=digest,
            )
        )
        assert row["position"] == 3

    def test_two_services_have_independent_orders(self):
        self._add("reddit")
        self._add("instagram")
        assert [row["position"] for row in _rows("instagram")] == [0, 1, 2]
        assert asyncio.run(db.services_with_cookies()) == ["instagram", "reddit"]

    def test_a_replacement_keeps_the_position_and_clears_the_verdict(self):
        rows = self._add()
        target = rows[1]
        asyncio.run(db.record_cookie_check(int(target["id"]), "ok"))

        new_name, digest, size = service_cookies.write_cookie_file("reddit", NETSCAPE)
        assert asyncio.run(
            db.update_service_cookie_file(
                int(target["id"]),
                stored_name=new_name,
                original_name="fresh.txt",
                size=size,
                sha256=digest,
            )
        ) is True

        replaced = asyncio.run(db.get_service_cookie(int(target["id"])))
        assert replaced is not None
        assert replaced["position"] == 1, "a replacement must not move the file"
        assert replaced["original_name"] == "fresh.txt"
        assert replaced["check_status"] is None, "a stale verdict is cleared"
        assert replaced["checked_at"] is None


