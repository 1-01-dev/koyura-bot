def _csrf(c: TestClient) -> str:
    return c.cookies.get("koyura_csrf") or ""


def _login(client: TestClient) -> TestClient:
    page = client.get("/login")
    assert page.status_code == 200, page.text
    resp = client.post(
        "/login",
        data={
            "username": "admin",
            "password": os.environ["ADMIN_PASSWORD"],
            "csrf_token": _csrf(client),
        },
        follow_redirects=False,
    )
    assert resp.status_code == 303, resp.text
    return client


def _root() -> Path:
    return Path(os.environ["COOKIES_PATH"])


def _disk_files(service: str) -> list[Path]:
    directory = _root() / service
    return sorted(directory.iterdir()) if directory.exists() else []


def _upload(
    client: TestClient,
    *,
    service: str = "reddit",
    data: bytes = NETSCAPE,
    name: str = "reddit-cookies.txt",
    action: str = "/admin/cookies/add",
    **extra: str,
):
    """POST one file upload exactly like the browser form does."""
    form: dict[str, str] = {"service": service, "csrf_token": _csrf(client)}
    form.update(extra)
    return client.post(
        action,
        data=form,
        files={"cookie_file": (name, data, "text/plain")},
        follow_redirects=False,
    )


def _rows(service: str | None = None) -> list[dict]:
    return asyncio.run(db.list_service_cookies(service))


