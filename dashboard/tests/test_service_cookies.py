class TestValidation:
    def test_a_real_netscape_jar_is_accepted(self):
        service_cookies.validate_payload(NETSCAPE)

    def test_the_header_is_optional_when_the_rows_are_right(self):
        service_cookies.validate_payload(
            b".reddit.com\tTRUE\t/\tTRUE\t1893456000\tsession\tabc\n"
        )

    def test_an_empty_file_is_refused(self):
        with pytest.raises(service_cookies.CookieError, match="empty"):
            service_cookies.validate_payload(b"")

    def test_a_file_over_the_limit_is_refused(self):
        big = NETSCAPE + b"#" + b"x" * (service_cookies.MAX_COOKIE_BYTES + 10)
        with pytest.raises(service_cookies.CookieError, match="larger than"):
            service_cookies.validate_payload(big)

    def test_a_file_exactly_at_the_limit_is_accepted(self):
        """The boundary is inclusive: 1 MB is the documented maximum."""
        padding = b"#" + b"x" * (service_cookies.MAX_COOKIE_BYTES - len(NETSCAPE) - 1)
        service_cookies.validate_payload(NETSCAPE + padding)

    def test_a_binary_file_is_refused(self):
        with pytest.raises(service_cookies.CookieError, match="binary"):
            service_cookies.validate_payload(b"\x00\x01\x02")

    def test_a_json_file_is_refused_with_a_readable_sentence(self):
        with pytest.raises(service_cookies.CookieError) as caught:
            service_cookies.validate_payload(b'{"cookies": []}')
        assert "Netscape" in str(caught.value)

    def test_a_row_with_the_wrong_number_of_fields_is_refused(self):
        broken = b".reddit.com\tTRUE\t/\tTRUE\t1893456000\tsession\n"  # six, not seven
        with pytest.raises(service_cookies.CookieError, match="7 tab-separated"):
            service_cookies.validate_payload(broken)

    def test_a_header_only_file_is_refused(self):
        with pytest.raises(service_cookies.CookieError, match="no cookies"):
            service_cookies.validate_payload(b"# Netscape HTTP Cookie File\n")

    def test_comments_and_blank_lines_are_ignored(self):
        data = (
            b"# Netscape HTTP Cookie File\n"
            b"\n"
            b"# a comment in the middle\n"
            b".reddit.com\tTRUE\t/\tTRUE\t1893456000\tsession\tabc\n"
        )
        service_cookies.validate_payload(data)

    def test_looks_like_cookies_answers_a_boolean(self):
        assert service_cookies.looks_like_cookies(NETSCAPE) is True
        assert service_cookies.looks_like_cookies(b"nope") is False


