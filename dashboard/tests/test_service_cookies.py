class TestSanitisation:
    @pytest.mark.parametrize(
        "raw,expected",
        [
            ("reddit", "reddit"),
            ("Reddit", "reddit"),
            ("  REDDIT  ", "reddit"),
            ("1tv.ru", "1tv.ru"),
            ("abc/../x", "abc-x"),
            ("../../etc/passwd", "etc-passwd"),
            ("a b c", "a-b-c"),
            ("...", ""),
            ("", ""),
            (None, ""),
            ("reddit;rm -rf /", "reddit-rm-rf"),
        ],
    )
    def test_names_are_reduced_to_one_safe_component(self, raw, expected):
        if expected == "":
            with pytest.raises(service_cookies.CookieError):
                service_cookies.sanitise_service(raw)
        else:
            assert service_cookies.sanitise_service(raw) == expected

    def test_a_long_name_is_refused(self):
        with pytest.raises(service_cookies.CookieError, match="under"):
            service_cookies.sanitise_service("a" * 200)

    def test_traversal_cannot_leave_the_root(self):
        service = service_cookies.sanitise_service("../../etc/passwd")
        directory = service_cookies.service_dir(service)
        assert _root().resolve() in directory.resolve().parents
        assert directory.resolve() != Path("/etc")

    def test_a_stored_name_must_look_generated(self):
        for bad in ("../../x.txt", "x.txt", "A" * 8 + ".txt", "abc.txt"):
            with pytest.raises(service_cookies.CookieError):
                service_cookies.cookie_path("reddit", bad)

    def test_generated_names_are_unique_and_matched(self):
        first = service_cookies.new_stored_name()
        second = service_cookies.new_stored_name()
        assert first != second
        assert first.endswith(".txt")
        service_cookies.cookie_path("reddit", first)  # does not raise


