class TestDisk:
    def test_writing_creates_the_directory_and_a_0600_file(self):
        _name, digest, size = service_cookies.write_cookie_file("reddit", NETSCAPE)

        directory = _root() / "reddit"
        assert directory.is_dir()
        mode = directory.stat().st_mode & 0o777
        assert mode == 0o700, f"the service directory is {oct(mode)}"

        files = _disk_files("reddit")
        assert len(files) == 1
        assert files[0].stat().st_mode & 0o777 == 0o600
        assert files[0].read_bytes() == NETSCAPE
        assert size == len(NETSCAPE)
        assert len(digest) == 64  # sha256 hex

    def test_an_invalid_file_is_never_written(self):
        with pytest.raises(service_cookies.CookieError):
            service_cookies.write_cookie_file("reddit", b"not a cookie file")
        assert _disk_files("reddit") == []

    def test_deleting_removes_the_file_and_the_empty_directory(self):
        name, _digest, _size = service_cookies.write_cookie_file("reddit", NETSCAPE)
        assert service_cookies.remove_cookie_file("reddit", name) is True

        assert not (_root() / "reddit" / name).exists()
        assert not (_root() / "reddit").exists(), "an empty service directory is removed"

    def test_deleting_keeps_the_directory_when_other_files_remain(self):
        first, _d, _s = service_cookies.write_cookie_file("reddit", NETSCAPE)
        second, _d, _s = service_cookies.write_cookie_file("reddit", NETSCAPE)

        service_cookies.remove_cookie_file("reddit", first)
        assert service_cookies.service_files("reddit") == [second]
        assert (_root() / "reddit").is_dir()

    def test_deleting_a_missing_file_is_not_an_error(self):
        assert service_cookies.remove_cookie_file("reddit", "a" * 16 + ".txt") is False

    def test_a_refused_stored_name_never_deletes_anything(self):
        service_cookies.write_cookie_file("reddit", NETSCAPE)
        with pytest.raises(service_cookies.CookieError):
            service_cookies.remove_cookie_file("reddit", "../../x.txt")
        assert len(_disk_files("reddit")) == 1


