# The layout contract (390px, tap targets, no inline code)
# ---------------------------------------------------------------------------

class TestLayout:
    def _page(self, admin: TestClient) -> str:
        _upload(admin, name="first.txt")
        _upload(admin, name="second.txt")
        return admin.get("/admin/cookies").text

    def test_a_service_is_a_block_not_a_table_row(self, admin):
        """A <details> inside a table cell cannot fit a 390px screen."""
        body = self._page(admin)
        assert "cookie-services" in body
        assert "<details" in body
        # The service list is not a table: no rows to clip.
        assert '<table class="data-table cookies-table"' not in body

    def test_every_file_shows_its_order_and_its_actions(self, admin):
        body = self._page(admin)
        assert 'class="cookie-file-order mono"' in body
        for action in ("/admin/cookies/move", "/admin/cookies/delete",
                       "/admin/cookies/replace", "/admin/cookies/check"):
            assert f'action="{action}"' in body, action

    def test_the_forms_carry_csrf_and_are_multipart_where_needed(self, admin):
        body = self._page(admin)
        assert body.count('name="csrf_token"') >= 5
        assert 'action="/admin/cookies/replace"' in body
        # The replace form uploads a file, so it must be multipart.
        replace_form = body[body.index('action="/admin/cookies/replace"') - 200:]
        assert 'enctype="multipart/form-data"' in replace_form

    def test_no_inline_handler_or_inline_script(self, admin):
        body = self._page(admin)
        for forbidden in ("onclick=", "onchange=", "onsubmit=", "<script>"):
            assert forbidden not in body, forbidden

    def test_the_stylesheet_gives_every_control_a_44px_target(self):
        css = (DASHBOARD_DIR / "static" / "style.css").read_text()
        start = css.index("/* ----- Cookies (admin")
        block = css[start:]
        # Every interactive class in the cookies block declares a 44px target.
        for selector in (
            ".cookies-add-btn",
            ".cookies-file-input",
            ".cookie-icon-btn",
            ".cookie-form-btn",
            ".cookies-input",
        ):
            assert selector in block, selector
        assert block.count("min-height: 44px") >= 5
        # The summary row is the whole row's tap target.
        summary = block[block.index(".cookies-summary {"):]
        assert "min-height: 52px" in summary.split("}")[0]

    def test_the_cookies_block_sets_no_colour_literal(self):
        import re as _re

        css = (DASHBOARD_DIR / "static" / "style.css").read_text()
        block = css[css.index("/* ----- Cookies (admin"):]
        found = _re.findall(r"#[0-9a-fA-F]{3,8}\b|\brgba?\(\s*\d|\bhsla?\(\s*\d",
                            block)
        assert not found, f"the cookies block hard-codes colours: {found[:5]}"
