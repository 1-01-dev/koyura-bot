class TestSecrecy:
    def test_the_database_never_holds_cookie_content(self, admin):
        _upload(admin)
        import sqlite3

        with sqlite3.connect(os.environ["DB_PATH"]) as connection:
            dump = "\n".join(
                str(row) for row in connection.execute("SELECT * FROM service_cookies")
            )
        assert SECRET_COOKIE_VALUE not in dump
        assert "reddit.com" not in dump, "even the domain is not stored"

    def test_no_log_line_carries_cookie_content(self, admin, caplog):
        with caplog.at_level(logging.DEBUG):
            _upload(admin)
            row = _rows("reddit")[0]
            admin.post(
                "/admin/cookies/delete",
                data={"csrf_token": _csrf(admin), "cookie_id": str(row["id"])},
                follow_redirects=False,
            )
        text = "\n".join(record.getMessage() for record in caplog.records)
        assert SECRET_COOKIE_VALUE not in text
        assert ".reddit.com\tTRUE" not in text

    def test_the_page_never_renders_cookie_content(self, admin):
        _upload(admin)
        body = admin.get("/admin/cookies").text
        assert SECRET_COOKIE_VALUE not in body
        assert "\tTRUE\t" not in body

    def test_no_response_serves_a_file(self, admin):
        """There is no route that hands a jar back; only metadata is public."""
        _upload(admin)
        row = _rows("reddit")[0]
        for path in (
            f"/admin/cookies/{row['id']}",
            f"/api/cookies/{row['id']}",
            f"/cookies/reddit/{row['stored_name']}",
        ):
            assert admin.get(path, follow_redirects=False).status_code in (301, 303, 404)


