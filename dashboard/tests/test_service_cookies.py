class TestPage:
    def test_the_page_needs_a_session(self):
        response = TestClient(app).get("/admin/cookies", follow_redirects=False)
        assert response.status_code == 303
        assert response.headers["location"] == "/login"

    def test_the_page_renders_the_form_and_the_suggestions(self, admin):
        body = admin.get("/admin/cookies").text
        assert 'id="cookie-add-form"' in body
        assert 'enctype="multipart/form-data"' in body
        assert 'list="service-suggestions"' in body
        # yt-dlp knows reddit; a suggestion must be there without a network call.
        assert 'value="reddit"' in body

    def test_uploading_adds_the_row_and_the_file(self, admin):
        response = _upload(admin)
        assert response.status_code == 303, response.text
        assert "added=1" in response.headers["location"]

        rows = _rows("reddit")
        assert len(rows) == 1
        assert rows[0]["original_name"] == "reddit-cookies.txt"
        assert rows[0]["size"] == len(NETSCAPE)
        assert len(rows[0]["sha256"]) == 64
        assert len(_disk_files("reddit")) == 1

    def test_the_table_shows_the_service_and_its_files(self, admin):
        _upload(admin)
        body = admin.get("/admin/cookies").text
        assert "reddit" in body
        assert "reddit-cookies.txt" in body
        assert 'id="cookies-empty"' not in body

    def test_a_bad_file_is_refused_and_nothing_is_stored(self, admin):
        response = _upload(admin, data=b'{"not": "cookies"}')
        assert response.status_code == 303
        assert "cookies_error" in response.headers["location"]
        assert _rows("reddit") == []
        assert _disk_files("reddit") == []

    def test_the_service_name_in_the_form_is_sanitised(self, admin):
        _upload(admin, service="../../etc/passwd")
        services = asyncio.run(db.services_with_cookies())
        assert services == ["etc-passwd"]
        assert (_root() / "etc-passwd").is_dir()
        assert not (Path("/etc") / "passwd").with_suffix(".txt").exists()

    def test_a_second_upload_appends_a_second_file(self, admin):
        _upload(admin, name="first.txt")
        _upload(admin, name="second.txt")
        rows = _rows("reddit")
        assert [row["original_name"] for row in rows] == ["first.txt", "second.txt"]
        assert [row["position"] for row in rows] == [0, 1]

    def test_moving_through_the_endpoint_reorders_the_table(self, admin):
        _upload(admin, name="first.txt")
        _upload(admin, name="second.txt")
        second = _rows("reddit")[1]

        response = admin.post(
            "/admin/cookies/move",
            data={
                "csrf_token": _csrf(admin),
                "cookie_id": str(second["id"]),
                "direction": "up",
            },
            follow_redirects=False,
        )
        assert response.status_code == 303
        assert [row["original_name"] for row in _rows("reddit")] == [
            "second.txt", "first.txt",
        ]

    def test_replacing_swaps_the_bytes_and_removes_the_old_file(self, admin):
        _upload(admin)
        row = _rows("reddit")[0]
        old_files = {path.name for path in _disk_files("reddit")}

        replacement = NETSCAPE.replace(b"fixture-session-value", b"brand-new-value")
        response = _upload(
            admin,
            data=replacement,
            name="fresh.txt",
            action="/admin/cookies/replace",
            cookie_id=str(row["id"]),
        )
        assert response.status_code == 303
        assert "replaced=1" in response.headers["location"]

        updated = _rows("reddit")[0]
        assert updated["original_name"] == "fresh.txt"
        assert updated["sha256"] != row["sha256"]
        remaining = {path.name for path in _disk_files("reddit")}
        assert remaining != old_files
        assert len(remaining) == 1, "the replaced file is gone from the disk"

    def test_deleting_removes_the_row_and_the_file(self, admin):
        _upload(admin)
        row = _rows("reddit")[0]
        stored = _disk_files("reddit")[0].name

        response = admin.post(
            "/admin/cookies/delete",
            data={"csrf_token": _csrf(admin), "cookie_id": str(row["id"])},
            follow_redirects=False,
        )
        assert response.status_code == 303
        assert _rows("reddit") == []
        assert not (_root() / "reddit" / stored).exists()

    def test_deleting_a_whole_service_removes_every_file(self, admin):
        _upload(admin, name="first.txt")
        _upload(admin, name="second.txt")

        response = admin.post(
            "/admin/cookies/delete-service",
            data={"csrf_token": _csrf(admin), "service": "reddit"},
            follow_redirects=False,
        )
        assert response.status_code == 303
        assert _rows("reddit") == []
        assert not (_root() / "reddit").exists()

    def test_check_stores_the_verdict(self, admin, monkeypatch):
        _upload(admin)
        row = _rows("reddit")[0]
        monkeypatch.setattr(
            service_cookies, "probe_cookie", lambda path, url, **kw: ("auth", "login required")
        )

        response = admin.post(
            "/admin/cookies/check",
            data={
                "csrf_token": _csrf(admin),
                "cookie_id": str(row["id"]),
                "test_url": "https://www.reddit.com/r/test/comments/x/",
            },
            follow_redirects=False,
        )
        assert response.status_code == 303
        updated = _rows("reddit")[0]
        assert updated["check_status"] == "auth"
        assert updated["checked_at"]

    def test_check_refuses_a_url_that_is_not_http(self, admin, monkeypatch):
        _upload(admin)
        row = _rows("reddit")[0]
        called = []
        monkeypatch.setattr(
            service_cookies, "probe_cookie",
            lambda *a, **kw: called.append(1) or ("ok", ""),
        )
        response = admin.post(
            "/admin/cookies/check",
            data={
                "csrf_token": _csrf(admin),
                "cookie_id": str(row["id"]),
                "test_url": "file:///etc/passwd",
            },
            follow_redirects=False,
        )
        assert response.status_code == 303
        assert not called, "a non-http URL must never reach yt-dlp"

    def test_every_cookie_endpoint_refuses_a_missing_csrf(self, admin):
        _upload(admin)
        row = _rows("reddit")[0]
        for action, payload in (
            ("/admin/cookies/add", {"service": "reddit"}),
            ("/admin/cookies/delete", {"cookie_id": str(row["id"])}),
            ("/admin/cookies/move", {"cookie_id": str(row["id"]), "direction": "up"}),
            ("/admin/cookies/delete-service", {"service": "reddit"}),
        ):
            response = admin.post(action, data=payload, follow_redirects=False)
            assert response.status_code == 303, action
            assert "cookies_error" in response.headers["location"], action

    def test_the_endpoints_need_a_session(self):
        anonymous = TestClient(app)
        for action in ("/admin/cookies/add", "/admin/cookies/delete"):
            response = anonymous.post(action, data={}, follow_redirects=False)
            assert response.status_code == 303
            assert response.headers["location"] == "/login"


