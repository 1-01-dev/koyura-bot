"""Service cookies: validation, storage, order, and the page's endpoints.

The cookie editor is the one place in the panel that writes a file a *person*
supplied into a directory the *engine* reads, so the tests here are about the
three things that could go wrong quietly:

* **the file is a cookie jar or it is refused** — a text file with the wrong
  shape would be accepted by yt-dlp and then fail every download in a way
  nobody can debug from the chat;
* **the service name is a path component** — ``../../etc`` must never leave
  ``COOKIES_PATH``, whatever a form submits;
* **cookie content never leaves the disk** — no log line, no database column,
  no API field, no rendered page.

Environment must be set BEFORE importing auth/main/db, like the other dashboard
test modules.
"""
